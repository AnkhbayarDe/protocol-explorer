import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { root, catalog } from './mn-catalog.mjs';
import { patterns } from './mn-patterns.mjs';

export async function build({ check = false } = {}) {
  const strings = JSON.parse(fs.readFileSync(path.join(root, 'localization/translations_mn.json'), 'utf8'));
  const preserved = new Set(JSON.parse(fs.readFileSync(path.join(root, 'localization/mn-preserved.json'), 'utf8')));
  const { required } = await catalog();
  const errors = [];
  const tokens = value => [...value.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');
  for (const [key, value] of Object.entries(strings)) {
    if (typeof value !== 'string' || !value.trim()) errors.push(`Empty translation: ${key}`);
    else if (tokens(key) !== tokens(value)) errors.push(`Placeholder mismatch: ${key}`);
    else if (!/[\u0400-\u04ff]/u.test(value) && !preserved.has(key)) errors.push(`Unreviewed untranslated value: ${key}`);
  }
  for (const key of required) {
    if (!Object.hasOwn(strings, key) && !preserved.has(key) && !patterns.some(([re]) => re.test(key))) errors.push(`Missing: ${key}`);
  }
  for (const key of preserved) if (Object.hasOwn(strings, key) && strings[key] !== key) errors.push(`Translated key incorrectly marked preserved: ${key}`);
  if (errors.length) throw new Error(errors.join('\n'));
  const patternCode = patterns.map(([re, replacement]) => `  [${re.toString()}, ${typeof replacement === 'function' ? replacement.toString() : JSON.stringify(replacement)}]`).join(',\n');
  const output = `// Generated by localization/build_mn_module.mjs. Edit translations_mn.json or mn-patterns.mjs.\nconst strings = ${JSON.stringify(strings, null, 2)};\nconst patterns = [\n${patternCode}\n];\nexport default { strings, patterns };\n`;
  const target = path.join(root, 'assets/mn.js');
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('assets/mn.js is stale; run npm run build:mn');
  } else fs.writeFileSync(target, output, 'utf8');
  console.log(`Mongolian: ${Object.keys(strings).length} translations, ${patterns.length} patterns, ${preserved.size} reviewed technical values; ${required.length} catalog entries checked.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  build({ check: process.argv.includes('--check') }).catch(error => { console.error(error.message); process.exitCode = 1; });
}
